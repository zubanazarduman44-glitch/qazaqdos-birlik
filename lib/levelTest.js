// Нәтиже: әр деңгей бойынша дұрыс жауап саны → ең жоғарғы қатарынан өткен деңгей
export function grade(answers) {
  const per = {};
  for (const l of LEVELS) per[l] = { ok: 0, n: 0 };
  QUESTIONS.forEach((q, i) => {
    per[q.lvl].n++;
    if (answers[i] === q.a) per[q.lvl].ok++;
  });
  let cefr = "A0";
  for (const l of LEVELS) {
    if (per[l].ok >= PASS[l]) cefr = l;
    else break;
  }
  const total = Object.values(per).reduce((a, x) => a + x.ok, 0);
  return { cefr, per, total, count: QUESTIONS.length };
}
