// Сұраққа жауап берілген соң көрсетілетін дәлел: key кездесетін толық сөйлем
export function keySentence(id, key) {
  const parts = HIST_TEXT[id]?.parts || [];
  for (const p of parts) {
    const i = p.indexOf(key);
    if (i < 0) continue;
    const sents = p.split(/(?<=[.!?])(?<!б\.з\.д\.)\s+/);
    let pos = 0;
    for (const s of sents) {
      if (i >= pos && i < pos + s.length + 1) return s;
      pos += s.length + 1;
    }
    return p;
  }
  return "";
}
