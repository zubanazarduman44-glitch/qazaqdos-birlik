let pass = 0;
const fails = [];
const eq = (name, got, want) => (got === want ? pass++ : fails.push(`${name}: got «${got}», want «${want}»`));

for (const [form, list] of Object.entries(CASES)) {
  for (const pair of list.split("|")) {
    const [w, want] = pair.split(" ");
    eq(`${form} ${w}`, attach(w, form)?.result, want);
  }
}
const pairCount = pass + fails.length;

// Үндестік пен соңғы дыбыс тобы
for (const [w, h] of [["тау", "back"], ["үй", "front"], ["ауыл", "back"], ["киім", "front"], ["қоян", "back"], ["керуен", "front"], ["оқулық", "back"], ["белбеу", "front"], ["су", null], ["би", null], ["аю", null], ["бару", null], ["ит", null]]) eq(`harmony ${w}`, harmony(w), h);
for (const [w, c] of [["тау", "R"], ["су", "V"], ["үй", "R"], ["көл", "L"], ["таң", "N"], ["қыз", "Z"], ["кітап", "T"], ["қала", "V"], ["жер", "R"], ["клуб", "T"]]) eq(`class ${w}`, endClass(w), c);
eq("twin лар", twin("pl", "лар"), "лер");
eq("twin нің", twin("gen", "нің"), "ның");
eq("twin мен", twin("ins", "мен"), null);
eq("voiced кітап", attach("кітап", "p1").voiced?.join(">"), "п>б");
eq("unsupported су", attach("су", "pl"), null);

// Тізімдегі әр сөз әр формада жалғанады, жалғау нұсқалар ішінде, жауап нұсқалары қайталанбайды
let combos = 0;
for (const w of NOUNS) {
  for (const f of FORMS) {
    if (!allowed(w, f)) continue;
    combos++;
    const r = attach(w, f);
    if (!r || !VARIANTS[f].includes(r.suffix)) {
      fails.push(`list ${f} ${w}: ${r?.result}`);
      continue;
    }
    for (const n of [3, 4]) {
      const o = optionsFor(f, r.suffix, n);
      if (new Set(o).size !== o.length || !o.includes(r.suffix) || o.length !== Math.min(n, VARIANTS[f].length)) fails.push(`options ${f} ${w}: ${o}`);
    }
  }
}
if (new Set(NOUNS).size !== NOUNS.length) fails.push("duplicate nouns: " + NOUNS.filter((w, i) => NOUNS.indexOf(w) !== i));

console.log(`word→form pairs: ${pairCount}; assertions passed: ${pass}; list combos checked: ${combos} (${NOUNS.length} nouns)`);
if (fails.length) {
  console.log("FAILED " + fails.length + ":\n" + fails.join("\n"));
  process.exit(1);
}
console.log("ALL PASS");
